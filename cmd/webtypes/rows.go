// The rows the server sends as stored: rows.gen.ts.

package main

import (
	"fmt"
	"reflect"
	"strconv"
	"strings"

	"github.com/agrigoryan/quadit/internal/core"
	"github.com/agrigoryan/quadit/internal/engine"
	"github.com/agrigoryan/quadit/internal/store"
)

// rowTypes are the Go types rows.gen.ts is written from: the row of every
// table (store.Tables), which covers every kind of row the reads give as
// stored (internal/server/rowkinds.go) and the tasks, events, workspace and
// users they give besides; a table whose rows are never sent costs an
// interface no one checks against, and a new table needs no choice here.
// After them, the answers that are plain structs of their own: a change's
// result.
func rowTypes() []reflect.Type {
	var types []reflect.Type
	for _, table := range store.Tables() {
		types = append(types, table.Type)
	}
	return append(types, reflect.TypeFor[engine.Result]())
}

// rowsSource is the whole of rows.gen.ts, written as Prettier would format
// it.
func rowsSource() string {
	w := &writer{named: map[string]reflect.Type{}, rows: true}
	for _, t := range rowTypes() {
		w.typeOf(t, 0)
	}
	var b strings.Builder
	b.WriteString(`// Code generated by "make generate" (cmd/webtypes) from the server's row
// structs (internal/core, and engine.Result). DO NOT EDIT.
//
// Each row as the server writes it: a field with "?" may be left out, and
// one that may be null says so. The app does not use these: its wire types
// are the hand-written ones beside this file, and rows.check.ts holds each
// of them to its twin here, so that a field added, renamed or retyped on
// the server fails the type check until the web type follows.
`)
	w.writeNamed(&b)
	for _, list := range valueLists {
		words := make([]string, len(list.values))
		for i, v := range list.values {
			words[i] = strconv.Quote(v)
		}
		fmt.Fprintf(&b, "\n/** %s */\nexport type %s = %s;\n", list.doc, list.name, strings.Join(words, " | "))
	}
	return b.String()
}

// valueLists are the fields whose value is one of a list the server knows,
// written as a union of the words: rows.check.ts holds the web's narrowed
// union for the field to it both ways, which a field's own check cannot (a
// union that leaves a word out is still a string). A list joins here when
// the server keeps it in one place.
var valueLists = []struct {
	name, doc string
	values    []string
}{
	{"LinkKind", "What a task link may point at: TaskLink.kind (core.LinkKinds).", core.LinkKinds},
}
